def _gen_interlock(tag: str, defn: dict, sp: dict, doc_ref: str,
                   sections: dict) -> str:
    """Generate interlock function block from section text."""
    desc = defn.get("description", f"{tag} safety interlock")[:80]

    # Try to find the interlock section content
    il_text = ""
    for title, text in sections.items():
        if tag.upper() in title.upper() or tag.upper() in text.upper()[:500]:
            il_text = text[:1000]
            break

    # Extract initiating tag if visible
    init_tags = re.findall(r"\b([A-Z]{1,3}-[0-9]{1,4})\b", il_text)
    init_tag  = init_tags[0] if init_tags else "SENSOR_INPUT"
    trip_v, trip_u = _get_setpoint(init_tag, "trip", sp, 0.0)

    return f"""\
(* ═══════════════════════════════════════════════════════════════════
   TAG  : {tag}
   TYPE : Safety Interlock / Protective Function
   DESC : {desc}
   FROM : {doc_ref}
   AUTO-GENERATED by CND-Verify — VERIFIED, no findings
   ═══════════════════════════════════════════════════════════════════ *)

FUNCTION_BLOCK FB_{tag.replace('-','_')}_Interlock
VAR_INPUT
    (* Initiating conditions — connect process values here *)
    Process_Value  : REAL;   (* Primary measured value *)
    Trip_Setpoint  : REAL := {trip_v:.1f};   (* From CND setpoint table *)
    Manual_Reset   : BOOL;   (* Operator manual reset — HMI pushbutton *)
    Bypass_Active  : BOOL;   (* Maintenance bypass — requires key switch *)
END_VAR
VAR_OUTPUT
    Trip_Active    : BOOL;   (* Interlock tripped — latched *)
    Reset_Ready    : BOOL;   (* Conditions safe — ready to reset *)
    Bypassed       : BOOL;   (* Bypass active indicator *)
END_VAR
VAR
    Latched        : BOOL;   (* Internal trip latch *)
END_VAR

(* Bypass overrides normal logic — for maintenance only *)
IF Bypass_Active THEN
    Trip_Active := FALSE;
    Bypassed    := TRUE;
    RETURN;
END_IF;

Bypassed := FALSE;

(* Trip initiation — latch on trip condition *)
IF Process_Value > Trip_Setpoint THEN
    Latched := TRUE;
END_IF;

(* Manual reset — only when process value has returned to safe range *)
(* Process_Value < Trip_Setpoint * 0.8 ensures hysteresis *)
IF Latched AND Manual_Reset AND (Process_Value < Trip_Setpoint * 0.8) THEN
    Latched := FALSE;
END_IF;

Trip_Active  := Latched;
Reset_Ready  := Latched AND (Process_Value < Trip_Setpoint * 0.8);

END_FUNCTION_BLOCK
"""


# ── Generator dispatch ────────────────────────────────────────────────────────

_GENERATORS = {
    "PUMP":                    _gen_pump,
    "MOTOR":                   _gen_pump,
    "ON_OFF_VALVE":            _gen_on_off_valve,
    "VALVE":                   _gen_on_off_valve,
    "CONTROL_VALVE":           _gen_control_valve,
    "PRESSURE_TRANSMITTER":    _gen_pressure_transmitter,
    "PT":                      _gen_pressure_transmitter,
    "FLOW_TRANSMITTER":        _gen_flow_transmitter,
    "FT":                      _gen_flow_transmitter,
    "LEVEL_TRANSMITTER":       _gen_level_transmitter,
    "LT":                      _gen_level_transmitter,
    "TEMPERATURE_TRANSMITTER": _gen_temperature_transmitter,
    "TT":                      _gen_temperature_transmitter,
    "INTERLOCK":               None,   # special case — needs sections
}


def run_plc_generator(state: dict) -> dict:
    """
    Generate IEC 61131-3 ST code for all clean (no HIGH/CRITICAL finding) equipment.

    Returns state with:
      plc_code: {
        tag: {
          code:            ST source code string,
          equipment_class: "PUMP" | "VALVE" | ...
          page:            page tag was found on
          clean:           True
          findings_avoided: count of findings on OTHER tags
        }
      }
      plc_summary: {
        clean_count, dirty_count, generated_count, skipped_count
      }
    """
    all_findings: list[dict]  = state.get("all_findings", [])
    tag_inventory: list[str]  = state.get("tag_inventory", [])
    definition_map: dict      = state.get("definition_map", {})
    setpoint_index: dict      = state.get("setpoint_index", {})
    sections: dict            = state.get("sections", {})
    doc_path: str             = state.get("document_path", "")

    doc_name = Path(doc_path).stem if doc_path else "CND"
    doc_ref  = f"{doc_name} — auto-generated {datetime.now().strftime('%Y-%m-%d')}"

    # Build set of "dirty" tags — any tag mentioned in CRITICAL or HIGH finding
    dirty_tags: set[str] = set()
    for f in all_findings:
        sev = f.get("severity", "INFO")
        if sev in ("CRITICAL", "HIGH"):
            # Extract any ISA tags from description + quote
            text = f.get("description", "") + " " + f.get("quote", "")
            for tag in ISA_TAG_RE.findall(text):
                dirty_tags.add(tag)
            # Also dirty the section's tags if section clearly mentions a tag
            section = f.get("section_title", "")
            for tag in ISA_TAG_RE.findall(section):
                dirty_tags.add(tag)

    plc_code: dict[str, dict] = {}
    skipped: list[str]        = []

    for tag in sorted(tag_inventory):
        if tag in dirty_tags:
            skipped.append(tag)
            continue

        eq_class = _equip_class(tag, definition_map)
        defn     = definition_map.get(tag, {})
        sp       = setpoint_index

        # Skip unknown equipment — no template available
        if eq_class == "UNKNOWN":
            skipped.append(tag)
            continue

        # Generate code
        try:
            if eq_class == "INTERLOCK":
                code = _gen_interlock(tag, defn, sp, doc_ref, sections)
            else:
                gen_fn = _GENERATORS.get(eq_class)
                if gen_fn is None:
                    skipped.append(tag)
                    continue
                code = gen_fn(tag, defn, sp, doc_ref)

            plc_code[tag] = {
                "code":           code,
                "equipment_class": eq_class,
                "page":           defn.get("page", 0),
                "clean":          True,
                "dirty_tags_avoided": sorted(dirty_tags),
            }
            logger.info("PLC code generated for %s (%s)", tag, eq_class)

        except Exception as e:
            logger.warning("PLC generation failed for %s: %s", tag, e)
            skipped.append(tag)

    state["plc_code"] = plc_code
    state["plc_summary"] = {
        "clean_count":     len(plc_code),
        "dirty_count":     len(dirty_tags),
        "skipped_count":   len(skipped),
        "skipped_tags":    skipped,
        "dirty_tags":      sorted(dirty_tags),
        "generated_at":    datetime.now().isoformat(),
    }

    logger.info(
        "PLC generator: %d blocks generated, %d tags skipped (dirty or unknown)",
        len(plc_code), len(skipped),
    )
    return state
