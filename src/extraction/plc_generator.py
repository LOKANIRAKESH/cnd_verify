"""
src/extraction/plc_generator.py

Generates IEC 61131-3 Structured Text (ST) function blocks for equipment
that has NO high/critical findings from the verification agents.

Logic:
  1. Collect all tags that appear in CRITICAL or HIGH findings → "dirty" tags
  2. Clean tags = tag_inventory - dirty_tags
  3. For each clean tag, look up its equipment class from definition_map
  4. Generate appropriate ST function block template
  5. Fill in setpoint values from setpoint_index where available
  6. Return {tag: {code, equipment_class, page, reason_clean}} dict

Generated code follows IEC 61131-3 ST (Structured Text) — compatible with
CODESYS, TIA Portal, Studio 5000, and most modern PLCs.
"""

import re
import logging
from datetime import datetime
from pathlib import Path

logger = logging.getLogger("cnd_verify")

# Tag prefix → equipment class (fallback when definition_map is empty)
PREFIX_CLASS = {
    "P":  "PUMP",
    "M":  "MOTOR",
    "XV": "ON_OFF_VALVE",
    "FV": "CONTROL_VALVE",
    "PV": "CONTROL_VALVE",
    "TV": "CONTROL_VALVE",
    "LV": "CONTROL_VALVE",
    "PT": "PRESSURE_TRANSMITTER",
    "FT": "FLOW_TRANSMITTER",
    "LT": "LEVEL_TRANSMITTER",
    "TT": "TEMPERATURE_TRANSMITTER",
    "AT": "ANALYSER_TRANSMITTER",
    "ST": "SPEED_TRANSMITTER",
    "ZT": "POSITION_TRANSMITTER",
    "HS": "HAND_SWITCH",
    "LS": "LIMIT_SWITCH",
    "IL": "INTERLOCK",
    "AL": "ALARM",
}


def _tag_prefix(tag: str) -> str:
    """Extract equipment prefix from ISA tag (e.g., PT-101 → PT, P-101 → P)."""
    m = re.match(r"^([A-Z]+)-", tag)
    return m.group(1) if m else tag[:2]


def _equip_class(tag: str, definition_map: dict) -> str:
    defn = definition_map.get(tag, {})
    if defn.get("class") and defn["class"] != "UNKNOWN":
        return defn["class"]
    return PREFIX_CLASS.get(_tag_prefix(tag), "UNKNOWN")


def _get_setpoint(tag: str, param: str, setpoint_index: dict, default=None):
    """Safe lookup into setpoint_index."""
    sp = setpoint_index.get(tag, {})
    entry = sp.get(param)
    if entry and isinstance(entry, dict):
        return entry.get("value", default), entry.get("unit", "")
    return default, ""


# ── IEC 61131-3 ST Templates ──────────────────────────────────────────────────

def _gen_pump(tag: str, defn: dict, sp: dict, doc_ref: str) -> str:
    desc = defn.get("description", f"{tag} centrifugal pump")[:80]
    return f"""\
(* ═══════════════════════════════════════════════════════════════════
   TAG  : {tag}
   TYPE : Pump / Motor Drive
   DESC : {desc}
   FROM : {doc_ref}
   AUTO-GENERATED by CND-Verify — VERIFIED, no findings
   ═══════════════════════════════════════════════════════════════════ *)

FUNCTION_BLOCK FB_{tag.replace('-','_')}_Pump
VAR_INPUT
    Start_CMD     : BOOL;    (* Start command — from HMI or sequence *)
    Stop_CMD      : BOOL;    (* Stop command — from HMI or ESD *)
    Remote_Mode   : BOOL;    (* TRUE = remote/auto, FALSE = local *)
    All_Permissive: BOOL;    (* All startup permissives satisfied *)
    ESD_Trip      : BOOL;    (* Emergency shutdown active *)
END_VAR
VAR_OUTPUT
    Motor_Run     : BOOL;    (* Motor contactor energise output *)
    Run_Feedback  : BOOL;    (* Confirms motor running — for HMI *)
    Fault         : BOOL;    (* Fault status *)
END_VAR
VAR
    Start_Delay   : TON;     (* Anti-shock start delay — 5 s default *)
    Run_Confirm   : TON;     (* Run confirmation timeout *)
    Started       : BOOL;
END_VAR

(* Safety: ESD always overrides *)
IF ESD_Trip THEN
    Motor_Run := FALSE;
    Started   := FALSE;
    Start_Delay(IN := FALSE);

(* Normal stop *)
ELSIF Stop_CMD THEN
    Motor_Run := FALSE;
    Started   := FALSE;
    Start_Delay(IN := FALSE);

(* Start sequence — only if remote mode and all permissives OK *)
ELSIF Start_CMD AND Remote_Mode AND All_Permissive AND NOT Started THEN
    Start_Delay(IN := TRUE, PT := T#5S);
    IF Start_Delay.Q THEN
        Motor_Run := TRUE;
        Started   := TRUE;
    END_IF;
END_IF;

(* Run confirmation — raise fault if motor not confirmed within 10 s *)
Run_Confirm(IN := Started AND NOT Motor_Run, PT := T#10S);
Fault       := Run_Confirm.Q;
Run_Feedback:= Motor_Run;

END_FUNCTION_BLOCK
"""


def _gen_on_off_valve(tag: str, defn: dict, sp: dict, doc_ref: str) -> str:
    desc = defn.get("description", f"{tag} on/off valve")[:80]
    return f"""\
(* ═══════════════════════════════════════════════════════════════════
   TAG  : {tag}
   TYPE : On/Off Valve (XV / Solenoid)
   DESC : {desc}
   FROM : {doc_ref}
   AUTO-GENERATED by CND-Verify — VERIFIED, no findings
   ═══════════════════════════════════════════════════════════════════ *)

FUNCTION_BLOCK FB_{tag.replace('-','_')}_Valve
VAR_INPUT
    Open_CMD      : BOOL;    (* Open command *)
    Close_CMD     : BOOL;    (* Close command *)
    ESD_Close     : BOOL;    (* ESD forces close *)
    Permissive_Open: BOOL;   (* Permissive to open — interlock clearance *)
END_VAR
VAR_OUTPUT
    Open_Output   : BOOL;    (* Solenoid energise — opens valve *)
    Close_Output  : BOOL;    (* Spring return — de-energise to close *)
    Open_FB       : BOOL;    (* Open limit switch feedback *)
    Close_FB      : BOOL;    (* Closed limit switch feedback *)
    Fault         : BOOL;    (* Travel fault — no feedback within timeout *)
END_VAR
VAR
    Travel_Timer  : TON;     (* Valve travel timeout — 30 s *)
    Last_CMD      : BOOL;
END_VAR

(* ESD overrides all — fail-closed *)
IF ESD_Close THEN
    Open_Output  := FALSE;
    Close_Output := TRUE;
    Travel_Timer(IN := FALSE);

ELSIF Close_CMD OR NOT Permissive_Open THEN
    Open_Output  := FALSE;
    Close_Output := TRUE;

ELSIF Open_CMD AND Permissive_Open THEN
    Open_Output  := TRUE;
    Close_Output := FALSE;
END_IF;

(* Travel fault detection *)
Travel_Timer(
    IN := (Open_CMD AND NOT Open_FB) OR (Close_CMD AND NOT Close_FB),
    PT := T#30S
);
Fault := Travel_Timer.Q;

END_FUNCTION_BLOCK
"""


def _gen_control_valve(tag: str, defn: dict, sp: dict, doc_ref: str) -> str:
    desc = defn.get("description", f"{tag} control valve")[:80]
    return f"""\
(* ═══════════════════════════════════════════════════════════════════
   TAG  : {tag}
   TYPE : Modulating Control Valve (FV / PV / TV / LV)
   DESC : {desc}
   FROM : {doc_ref}
   AUTO-GENERATED by CND-Verify — VERIFIED, no findings
   ═══════════════════════════════════════════════════════════════════ *)

FUNCTION_BLOCK FB_{tag.replace('-','_')}_CtrlValve
VAR_INPUT
    SP            : REAL;    (* Setpoint — 0.0 to 100.0 % open *)
    Auto_Mode     : BOOL;    (* TRUE = auto/cascade, FALSE = manual *)
    Manual_SP     : REAL;    (* Manual setpoint override *)
    ESD_Close     : BOOL;    (* ESD — fail closed *)
    ESD_Open      : BOOL;    (* ESD — fail open *)
END_VAR
VAR_OUTPUT
    Output_Pct    : REAL;    (* Output to positioner — 0–100 % *)
    Fault         : BOOL;
END_VAR

IF ESD_Close THEN
    Output_Pct := 0.0;
ELSIF ESD_Open THEN
    Output_Pct := 100.0;
ELSIF Auto_Mode THEN
    Output_Pct := LIMIT(0.0, SP, 100.0);
ELSE
    Output_Pct := LIMIT(0.0, Manual_SP, 100.0);
END_IF;

END_FUNCTION_BLOCK
"""


def _gen_pressure_transmitter(tag: str, defn: dict, sp: dict, doc_ref: str) -> str:
    hi_hi_v, hi_hi_u = _get_setpoint(tag, "hi_hi", sp, 160.0)
    hi_v,    hi_u    = _get_setpoint(tag, "hi",    sp, 150.0)
    lo_v,    lo_u    = _get_setpoint(tag, "lo",    sp, 10.0)
    trip_v,  trip_u  = _get_setpoint(tag, "trip",  sp, hi_hi_v)
    unit = hi_u or hi_hi_u or "PSI"
    desc = defn.get("description", f"{tag} pressure transmitter")[:80]

    return f"""\
(* ═══════════════════════════════════════════════════════════════════
   TAG  : {tag}
   TYPE : Pressure Transmitter
   DESC : {desc}
   FROM : {doc_ref}
   AUTO-GENERATED by CND-Verify — VERIFIED, no findings
   ═══════════════════════════════════════════════════════════════════ *)

FUNCTION_BLOCK FB_{tag.replace('-','_')}_PT
VAR_INPUT
    Raw_Input     : INT;     (* 4–20 mA scaled to 0–32767 *)
    Range_Lo      : REAL := 0.0;
    Range_Hi      : REAL := 200.0;
END_VAR
VAR_OUTPUT
    PV            : REAL;    (* Measured value — {unit} *)
    Alarm_HH      : BOOL;    (* Priority 1 — process trip *)
    Alarm_HI      : BOOL;    (* Priority 2 — operator alert *)
    Alarm_LO      : BOOL;    (* Priority 3 — low pressure *)
    Trip_Signal   : BOOL;    (* Interlock trip output *)
    Bad_Signal    : BOOL;    (* Sensor fault — out of 4–20 mA range *)
END_VAR

(* Linearise 4-20 mA input to engineering units *)
PV := Range_Lo + (REAL(Raw_Input) / 32767.0) * (Range_Hi - Range_Lo);

(* Alarm evaluation — setpoints from CND setpoint table *)
Alarm_HH    := PV > {hi_hi_v:.1f};    (* {hi_hi_v:.1f} {unit} — from document *)
Alarm_HI    := PV > {hi_v:.1f};       (* {hi_v:.1f} {unit} — from document *)
Alarm_LO    := PV < {lo_v:.1f};       (* {lo_v:.1f} {unit} — from document *)
Trip_Signal := PV > {trip_v:.1f};     (* {trip_v:.1f} {unit} — trip setpoint *)

(* Sensor health check — input below 4 mA or above 20 mA *)
Bad_Signal  := Raw_Input < 820 OR Raw_Input > 31130;

END_FUNCTION_BLOCK
"""


def _gen_flow_transmitter(tag: str, defn: dict, sp: dict, doc_ref: str) -> str:
    hi_v, hi_u = _get_setpoint(tag, "hi",    sp, 100.0)
    lo_v, lo_u = _get_setpoint(tag, "lo",    sp, 5.0)
    unit = hi_u or lo_u or "L/MIN"
    desc = defn.get("description", f"{tag} flow transmitter")[:80]

    return f"""\
(* ═══════════════════════════════════════════════════════════════════
   TAG  : {tag}
   TYPE : Flow Transmitter
   DESC : {desc}
   FROM : {doc_ref}
   AUTO-GENERATED by CND-Verify — VERIFIED, no findings
   ═══════════════════════════════════════════════════════════════════ *)

FUNCTION_BLOCK FB_{tag.replace('-','_')}_FT
VAR_INPUT
    Raw_Input     : INT;
    Range_Lo      : REAL := 0.0;
    Range_Hi      : REAL := 200.0;
END_VAR
VAR_OUTPUT
    PV            : REAL;    (* {unit} *)
    Alarm_HI      : BOOL;
    Alarm_LO      : BOOL;
    No_Flow       : BOOL;    (* Low flow alarm — potential blocked line *)
    Bad_Signal    : BOOL;
END_VAR

PV        := Range_Lo + (REAL(Raw_Input) / 32767.0) * (Range_Hi - Range_Lo);
Alarm_HI  := PV > {hi_v:.1f};   (* {hi_v:.1f} {unit} *)
Alarm_LO  := PV < {lo_v:.1f};   (* {lo_v:.1f} {unit} *)
No_Flow   := PV < 1.0;
Bad_Signal:= Raw_Input < 820 OR Raw_Input > 31130;

END_FUNCTION_BLOCK
"""


def _gen_level_transmitter(tag: str, defn: dict, sp: dict, doc_ref: str) -> str:
    hi_v, hi_u = _get_setpoint(tag, "hi", sp, 80.0)
    lo_v, lo_u = _get_setpoint(tag, "lo", sp, 10.0)
    unit = hi_u or lo_u or "%"
    desc = defn.get("description", f"{tag} level transmitter")[:80]

    return f"""\
(* ═══════════════════════════════════════════════════════════════════
   TAG  : {tag}
   TYPE : Level Transmitter
   DESC : {desc}
   FROM : {doc_ref}
   AUTO-GENERATED by CND-Verify — VERIFIED, no findings
   ═══════════════════════════════════════════════════════════════════ *)

FUNCTION_BLOCK FB_{tag.replace('-','_')}_LT
VAR_INPUT
    Raw_Input     : INT;
    Range_Lo      : REAL := 0.0;
    Range_Hi      : REAL := 100.0;
END_VAR
VAR_OUTPUT
    PV            : REAL;    (* {unit} *)
    Alarm_HH      : BOOL;    (* Overflow risk *)
    Alarm_HI      : BOOL;
    Alarm_LO      : BOOL;    (* Low level — pump cavitation risk *)
    Alarm_LL      : BOOL;    (* Very low — pump protection trip *)
    Bad_Signal    : BOOL;
END_VAR

PV        := Range_Lo + (REAL(Raw_Input) / 32767.0) * (Range_Hi - Range_Lo);
Alarm_HH  := PV > {min(hi_v * 1.1, 95.0):.1f};
Alarm_HI  := PV > {hi_v:.1f};
Alarm_LO  := PV < {lo_v:.1f};
Alarm_LL  := PV < {max(lo_v * 0.5, 5.0):.1f};
Bad_Signal:= Raw_Input < 820 OR Raw_Input > 31130;

END_FUNCTION_BLOCK
"""


